#!/usr/bin/env node
/**
 * Build server/mcp/gatewayApiCatalog.js — the compact, read-only Gateway API
 * index that the MCP `search_gateway_api` and `call_gateway_api` tools serve.
 *
 *   node scripts/build-mcp-api-catalog.mjs
 *
 * Source is the Gateway's published OpenAPI document (public/swagger.json). Only
 * GET operations are indexed; write methods never reach the catalogue, so the
 * passthrough cannot be talked into one. The output is committed because the
 * production image copies `server/` but not `public/`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const swagger = JSON.parse(fs.readFileSync(path.join(root, 'public/swagger.json'), 'utf8'));

const trim = (s, n) => {
  const t = String(s ?? '')
    .replace(/\s+/g, ' ')
    .trim();
  return t.length > n ? `${t.slice(0, n - 1)}…` : t;
};

function schemaType(p) {
  const s = p.schema ?? p;
  if (s.enum) return { type: s.type ?? 'string', enum: s.enum };
  if (s.type === 'array') return { type: 'array', items: s.items?.type ?? 'string' };
  return { type: s.type ?? 'string' };
}

const operations = [];
for (const [p, item] of Object.entries(swagger.paths)) {
  const op = item.get;
  if (!op) continue;
  const params = [...(item.parameters ?? []), ...(op.parameters ?? [])]
    .filter((x) => x && (x.in === 'path' || x.in === 'query'))
    .map((x) => ({
      name: x.name,
      in: x.in,
      required: Boolean(x.required || x.in === 'path'),
      ...schemaType(x),
      ...(x.description ? { description: trim(x.description, 120) } : {}),
    }));
  operations.push({
    path: p,
    tag: (op.tags ?? ['Other'])[0],
    summary: trim(op.summary, 140),
    ...(op.description && trim(op.description, 240) !== trim(op.summary, 240)
      ? { description: trim(op.description, 240) }
      : {}),
    params,
  });
}
operations.sort((a, b) => a.path.localeCompare(b.path));

const out = {
  source: `${swagger.info?.title ?? 'Gateway REST API'} ${swagger.info?.version ?? ''}`.trim(),
  basePath: '/management',
  operations,
};
// A JS module, not JSON: JSON imports need import attributes, which older Node
// runtimes reject, and reading a file beside the module breaks under jsdom tests.
const dest = path.join(root, 'server/mcp/gatewayApiCatalog.js');
fs.writeFileSync(
  dest,
  `// Generated by scripts/build-mcp-api-catalog.mjs from public/swagger.json. Do not edit.\n/* eslint-disable */\nexport default ${JSON.stringify(out, null, 1)};\n`
);
console.log(`${operations.length} GET operations -> ${path.relative(root, dest)}`);
